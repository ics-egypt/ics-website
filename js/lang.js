function setLanguage(lang) {
    if (!translations[lang]) lang = 'ar';
    localStorage.setItem('ics_lang', lang);

    const isRtl = (lang === 'ar');
    document.documentElement.lang = lang;
    document.documentElement.dir = isRtl ? 'rtl' : 'ltr';

    // Update all elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang][key]) {
            el.innerHTML = translations[lang][key];
        }
    });

    // Update language toggle button text
    const langBtnText = document.getElementById('lang-btn-text');
    if (langBtnText) {
        langBtnText.textContent = translations[lang].lang_btn;
    }

    // Update arrows direction
    document.querySelectorAll('.btn-arrow').forEach(arrow => {
        arrow.textContent = isRtl ? '←' : '→';
    });
}

document.addEventListener('DOMContentLoaded', () => {
    // Check saved language or default to Arabic
    const savedLang = localStorage.getItem('ics_lang') || 'ar';
    setLanguage(savedLang);

    // Attach click event to language button
    const langBtn = document.getElementById('lang-toggle-btn');
    if (langBtn) {
        langBtn.addEventListener('click', () => {
            const currentLang = localStorage.getItem('ics_lang') || 'ar';
            const nextLang = (currentLang === 'ar') ? 'en' : 'ar';
            setLanguage(nextLang);
        });
    }
});
